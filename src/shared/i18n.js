// Langues proposées dans les réglages (labels natifs, non traduits).
const LANGS = [
  { code: 'fr', label: 'Français' },
  { code: 'en', label: 'English' },
  { code: 'de', label: 'Deutsch' },
  { code: 'es', label: 'Español' },
  { code: 'it', label: 'Italiano' },
];

const LOCALES = { fr: 'fr-FR', en: 'en-GB', de: 'de-DE', es: 'es-ES', it: 'it-IT' };

let current = 'fr';

function setLang(code) {
  current = DICT[code] ? code : 'fr';
  return current;
}

function getLang() {
  return current;
}

// 'system' → langue du navigateur/OS (fr par défaut).
function resolveLang(setting, navigatorLanguage) {
  if (setting && setting !== 'system' && DICT[setting]) return setting;
  const n = String(navigatorLanguage || '').toLowerCase().slice(0, 2);
  return DICT[n] ? n : 'fr';
}

function t(key, vars) {
  let s = (DICT[current] && DICT[current][key]) || DICT.fr[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split('{' + k + '}').join(String(v));
    }
  }
  return s;
}

// Locale pour les dates (timeAgo, toLocaleDateString).
function locale() {
  return LOCALES[current] || 'fr-FR';
}

module.exports = { t, setLang, getLang, resolveLang, locale, LANGS };
